#!/usr/bin/env python3
"""Generate public references from the app checkout and its matching CLI binary."""
import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Contributor-only text that must never reach a public page.
LEAK = re.compile(r'RNABrowser-|\bTools/|\.\./\.\./|FOXKIT_NO_SKIP|SWT_EXPERIMENTAL|FoxCore|FoxKit|'
                  r'\bFox[A-Z]\w+|\b\w+\.swift\b|\bSources/|\bScripts/|\w+Tests\b|\bdark in\b|\bfaces?\b|\bMCP[A-Z]\w+\.|(?i:fianchetto|lindonlight|extendoptic|h3k27m|histone|\bdmg\b|dipg)|\brule M\d')
HEADER = '<!-- Generated by scripts/sync-docs.py; edit canonical app documentation. -->\n\n'


def section(text, heading, next_heading=None):
    lines = text.splitlines(keepends=True)
    start = next(i for i, line in enumerate(lines) if line.rstrip() == heading)
    end = next(i for i in range(start + 1, len(lines))
               if lines[i].rstrip() == next_heading) if next_heading else len(lines)
    return ''.join(lines[start:end]).strip() + '\n'


BEAD = r'RNABrowser-[a-z0-9]+(?:\.[0-9]+)*(?:, [a-z0-9]+(?:\.[0-9]+)+)*'


def cut(text, start, end, replacement=''):
    """Replace text from start up to (not including) end; fail loudly if the canonical text moved."""
    i = text.find(start)
    j = text.find(end, i + len(start)) if i >= 0 else -1
    if i < 0 or j < 0:
        raise ValueError(f'canonical text moved; update scripts/sync-docs.py: {start[:60]!r}')
    return text[:i] + replacement + text[j:]


def drop_contributor_notes(text):
    """Remove tracker IDs, test names and implementation type names that annotate canonical docs."""
    text = re.sub(r'\s*\(' + BEAD + r'\)', '', text)
    text = re.sub(r'\(' + BEAD + r'[;:] ', '(', text)
    text = re.sub(r',\s*' + BEAD + r'\)', ')', text)
    text = re.sub(r'\s*\(`\w+Tests(?:\.\w+)?` pins that\)', '', text)
    text = re.sub(r'\s*`\w+Tests` (?:holds|pins)[^.]*\.', '', text)
    text = re.sub(r'\s*\(`(?:Fox|Curated|Premium)[A-Z]\w*(?:\.\w+)?`(?:, both faces)?\)', '', text)
    text = text.replace(" with FoxCore's `CuratedPackageValidator`, the one authority for the data rules", '')
    text = text.replace('an assembled curated package (`Scripts/curated/assemble.py --out`: ', 'an assembled curated package (')
    text = text.replace('the same FoxCore calls the app', 'the same calls the app')
    text = re.sub(r'both app\s+faces', 'the apps', text).replace(' (`ExportFileName`)', '')
    text = text.replace('the PDF faces (', 'the PDF fonts (')
    text = text.replace(' (rule M29)', '')
    text = text.replace('`Tools/genefox/Resources` is copied into the shared `locus_GenefoxTools` resource bundle. It holds',
                        'The `locus_GenefoxTools` resource bundle holds')
    text = text.replace(" ([Tools/genefox-helper/README.md](../genefox-helper/README.md))", '')
    text = text.replace('Every write goes through `MCPOutputFiles.writeCreateOnly`:', 'Every write follows these rules:')
    text = re.sub(r'\s*\(`MCP[A-Z]\w*\.\w+`\)', '', text)
    text = text.replace('a stray `print` from FoxCore cannot', 'a stray `print` cannot')
    text = text.replace('--resources <dir> (a copy of Sources/Locus/Resources)', '--resources <dir>')
    text = text.replace(' See [docs/curated/DatasetPackage.md](../../docs/curated/DatasetPackage.md).', '')
    text = text.replace('See [docs/MCPServerGuide.md](../../docs/MCPServerGuide.md).', 'See the [MCP server guide](mcp.md#entitlements-genefox-pro).')
    text = text.replace('The override is installed through `FoxStorageLocationRegistry.cacheRoot`, which download\nand curated payload caches use',
                        'Download and curated payload caches use the override')
    return text


def drop_unreleased(text):
    """Keep public pages to features released in this version (compiled-dark and QA-only features stay out)."""
    if '## Numeric dose/time series (QA preview)' in text:
        text = cut(text, '## Numeric dose/time series (QA preview)', '## Rich shell arguments')
    if '- **Figure color scale (GeneFox Pro; dark in 1.1.0).**' in text:
        text = cut(text, '- **Figure color scale (GeneFox Pro; dark in 1.1.0).**', '- **A heatmap opened from a differential-expression result**')
        text = cut(text, '- **Figure annotations (GeneFox Pro; dark in 1.1.0).**', '- **Figure axes (GeneFox Pro).**')
    if 'This build registers three Pro tools' in text:
        text = cut(text, 'This build registers three Pro tools', '`account_status`\n',
                   'Pro tools: `batch_explorer_run`, `publication_studio_export`, `dataset_radar_check` and\n'
                   '`dose_response`. Without a live grant a Pro tool is not listed, and a direct call is refused\n'
                   'with `entitlement_required` before any file is opened. `genefox curated dose <view> <package-dir>`\n'
                   'runs `dose_response` from a terminal.\n\n')
        text = cut(text, 'Two account services have headless surfaces too', '## Account and cloud authority',
                   '`lab_collaboration_status`, `cloud_sync_status`, `cloud_sync_now` and `cloud_sync_store` are\n'
                   'free. They need a linked account, so in this version they report that none is linked.\n\n')
    return text


