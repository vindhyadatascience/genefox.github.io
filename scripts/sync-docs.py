def generate(app, binary):
    cli = (app / 'Tools/genefox/README.md').read_text()
    mcp = (app / 'docs/MCPServerGuide.md').read_text()
    plugin_root = app / 'Integrations/agent-plugins'
    plugin = (plugin_root / 'README.md').read_text()
    catalogue = subprocess.run([str(binary), 'tools'], check=True, capture_output=True,
                               text=True, timeout=30).stdout.strip()
    documented = mcp.split('<!-- BEGIN TOOL CATALOGUE -->\n', 1)[1].split('<!-- END TOOL CATALOGUE -->', 1)[0].strip()
    if catalogue != documented:
        raise ValueError('CLI catalogue differs from canonical MCP guide; use a binary built from the selected checkout.')
    install_intro = (ROOT / 'mkdocs/templates/install-intro.md').read_text()
    install = install_intro + '\n' + section(cli, '### The macOS app\'s copy', '## Resources')
    for start, end in [('### Scientific resources (`--resources <dir>` / `GENEFOX_RESOURCES`)', '### Bundled report resources'),
                       ('### Bundled report resources', '### Staging an install layout'),
                       ('### Download cache (`--cache-dir <dir>` / `GENEFOX_CACHE_DIR`)', '## Output files'),
                       ('## Output files', '## Subcommands and exit codes'),
                       ('## Environment variables', None)]:
        install += '\n' + section(cli, start, end)
    install = re.sub(r'^### ', '## ', install, flags=re.M)
    cli_page = '# CLI reference\n\nResource, cache and output directories are described in [Install & resources](install.md).\n\n' + section(cli, '## Subcommands and exit codes', '## Environment variables')
    intro = mcp.split('\nTo build and install the binary,', 1)[0].split('\n', 1)[1].strip().replace('FoxCore code', 'analysis code')
    mcp_page = '# MCP server guide\n\n' + intro + '\n\nSee [Install & resources](install.md) and the [CLI reference](cli.md).\n\n' + section(mcp, '## Starting the server', '## Tool catalogue')
    mcp_page += '\n## Tool catalogue\n\nSee the generated [tool catalogue](tools.md).\n\n'
    mcp_page += section(mcp, '## Argument conventions', '## Entitlements (GeneFox Pro)')
    entitlement = section(mcp, '## Entitlements (GeneFox Pro)', '## Account and cloud authority')
    entitlement = re.sub(r'The server \*\*fails closed\*\*\..*?This build registers',
                         'The server **fails closed**. Pro tools are listed and callable only when the server grants the required capability. Hidden tools answer `-32602 Unknown tool`. No argument, flag, environment variable or file grants Pro access.\n\nThis build registers', entitlement, flags=re.S)
    account = section(mcp, '## Account and cloud authority', '## Limits, deadlines and cancellation')
    account = re.sub(r'Account linking.*?Its state in this build:', 'Account linking, cloud retry and the dataset finder are **not available** in this build:', account, flags=re.S)
    account = re.sub(r'  The human account helper.*?are not built\.', '', account, flags=re.S)
    mcp_page += entitlement + '\n' + account + '\n' + section(mcp, '## Limits, deadlines and cancellation', '## Plugin')
    mcp_page += '\n## Plugins\n\nSee [Agent plugins](plugins.md) for the shared skills, launchers, setup and host configuration.\n'
    tool_intro = section(mcp, '## Tool catalogue', '## Argument conventions').split('<!-- BEGIN TOOL CATALOGUE -->', 1)[0]
    tool_intro = re.sub(r'`genefox tools` generates.*?The \*\*Access\*\*',
                        '`genefox tools` generates this table from the server registry. Run it to see the catalogue for your installed build.\n\nThe **Access**', tool_intro, flags=re.S)
    tools = tool_intro.replace('## Tool catalogue', '# Tool catalogue', 1) + '<!-- BEGIN TOOL CATALOGUE -->\n' + catalogue + '\n<!-- END TOOL CATALOGUE -->\n\nSee the [MCP guide](mcp.md) for arguments, results, limits and errors.\n'
    plugins = plugin.replace('[LICENSE](LICENSE)', '[LICENSE](assets/plugin-LICENSE.txt)').replace('[NOTICE](NOTICE)', '[NOTICE](assets/plugin-NOTICE.txt)')
    plugins = re.sub(r'You need a `genefox` CLI binary.*?`bin/genefox-locate.sh`',
                     'You need an installed `genefox` CLI binary with its resources; see [Install & resources](install.md). The commands below run from the plugin package directory.\n\n`bin/genefox-locate.sh`', plugins, flags=re.S)
    plugins = plugins.replace('From the repository root, add this directory as a marketplace', 'From the plugin package directory, add it as a marketplace')
    plugins = plugins.replace('From the repository root, register this package\'s marketplace', 'From the plugin package directory, register its marketplace')
    plugins = plugins.replace('./Integrations/agent-plugins', '.').replace('Run `Integrations/agent-plugins/bin/genefox-check`', 'Run `bin/genefox-check`')
    plugins = re.sub(r'This settles the design document\'s Codex discovery questions:.*?Repeat it after changing the plugin or upgrading Codex\.',
                     'After installation or a host upgrade, check skill discovery, run `bin/genefox-check`, then try an analysis and cancellation in a fresh session.', plugins, flags=re.S)
    plugins = re.sub(r"Codex reads `.agents/plugins/marketplace.json`;.*?With no plugin data folder,", 'With no plugin data folder,', plugins, flags=re.S)
    pages = {'install.md': install, 'cli.md': cli_page, 'mcp.md': mcp_page, 'tools.md': tools, 'plugins.md': plugins}
    leaks = []
    for name, content in pages.items():
        content = drop_unreleased(drop_contributor_notes(public(content)))
        for match in LEAK.finditer(content):
            line = content.count('\n', 0, match.start()) + 1
            leaks.append(f'{name}:{line}: {match.group(0)!r}')
        pages[name] = (HEADER + content.strip() + '\n').encode()
    if leaks:
        raise ValueError('contributor-only text remains:\n  ' + '\n  '.join(leaks))
    for name in ['LICENSE', 'NOTICE']:
        pages['assets/plugin-' + name + '.txt'] = (plugin_root / name).read_bytes()
    return pages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--app-repo', type=Path, required=True)
    parser.add_argument('--genefox', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='Fail if generated files differ; write nothing')
    args = parser.parse_args()
    pages = generate(args.app_repo.resolve(), args.genefox.resolve())
    stale = []
    for name, data in pages.items():
        path = ROOT / 'mkdocs/docs' / name
        if not path.exists() or path.read_bytes() != data:
            stale.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if args.check and stale:
        parser.exit(1, 'Generated docs differ: ' + ', '.join(stale) + '\n')
    print('Canonical references and CLI catalogue match; ' + (str(len(stale)) + ' files updated.' if not args.check else 'generated files are current.'))


if __name__ == '__main__':
    main()
